"""Canonical 36-stage and mathematical-operation registry for distributed semantics."""
from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Any


@dataclass(frozen=True, slots=True)
class OperationSpec:
    """Describe one traceable computation, its mathematics, and its qualified neural analogue."""

    operation_id: str
    name: str
    mathematical_operation: str
    functional_responsibility: str


@dataclass(frozen=True, slots=True)
class StageSpec:
    """Describe one master stage, its purpose, biological reference, and ordered operations."""

    stage_id: str
    stage_number: int
    name: str
    objective: str
    biological_reference: str
    operations: tuple[OperationSpec, ...]


def _stage(
    number: int,
    name: str,
    objective: str,
    biology: str,
    operations: tuple[tuple[str, str, str], ...],
) -> StageSpec:
    """Create a numbered stage and stable hierarchical operation identifiers."""
    prefix = f"DS-{number:02d}"
    return StageSpec(
        stage_id=prefix,
        stage_number=number,
        name=name,
        objective=objective,
        biological_reference=biology,
        operations=tuple(
            OperationSpec(
                operation_id=f"{prefix}.{index:02d}",
                name=operation_name,
                mathematical_operation=mathematics,
                functional_responsibility=responsibility,
            )
            for index, (operation_name, mathematics, responsibility) in enumerate(operations, 1)
        ),
    )


