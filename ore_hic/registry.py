OPERATION_REGISTRY: tuple[OperationSpec, ...] = tuple(
    OperationSpec(
        operation_id=row[0],
        phase=row[1],
        name=row[2],
        purpose=row[3],
        mathematical_form=row[4],
        inputs=row[5],
        outputs=row[6],
        evidence_level=row[7],
    )
    for row in _OPERATION_ROWS
)


def registry_as_dicts() -> list[dict[str, object]]:
    """Return the 52-operation registry as plain dictionaries."""
    return [spec.to_dict() for spec in OPERATION_REGISTRY]
