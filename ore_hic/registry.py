"""Canonical 52-operation registry for the HIC Point 16 pipeline.

The ordered operations follow the Point 16 specification: eight phases (A-H)
covering the fifty-two detailed steps. "Mathematical form" entries are the
specification's own models (Bayesian ranking, entropy and information gain,
the assignment ILP, Hoare triples), recorded as executable model abstractions,
not as claims about human cognition.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass


@dataclass(frozen=True, slots=True)
class OperationSpec:
    """Describe one HIC pipeline operation, its inputs, outputs, and basis."""

    operation_id: str
    phase: str
    name: str
    purpose: str
    mathematical_form: str
    inputs: tuple[str, ...]
    outputs: tuple[str, ...]
    evidence_level: str

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


