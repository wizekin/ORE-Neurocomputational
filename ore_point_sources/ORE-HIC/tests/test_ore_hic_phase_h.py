def test_step51_sandbox_executes_and_reports(completed_result):
    execution = completed_result.execution_report
    assert execution is not None
    assert execution.exit_code == 0
    statuses = {o.fixture_name: o.status for o in execution.outcomes}
    assert statuses.get("example") == "PASSED"
    assert statuses.get("empty-input-rejected") == "PASSED"
    # Policy is recorded: CPU/memory/wall limits and capability grants.
    policy = execution.policy.to_dict()
