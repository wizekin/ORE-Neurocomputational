def test_step50_source_maps_cover_required_nodes(completed_result):
    code = completed_result.code_artifact
    assert code is not None
    required = []
    ir = completed_result.algo_ir
    for node_type in (NodeType.OPERATION, NodeType.CONDITION, NodeType.LOOP,
                      NodeType.CONSTRAINT, NodeType.PRECONDITION, NodeType.TEST):
        required.extend(n.node_id for n in ir.nodes_of(node_type))
    _included, missing = code.source_map.coverage_of(required)
    assert not missing, f"nodes without source-map coverage: {missing}"
    # Line-level lookup works both ways.
    first_entry = code.source_map.entries[0]
    assert code.source_map.nodes_for_line(first_entry.start_line) == (first_entry.node_id,)
    assert code.source_map.lines_for_node(first_entry.node_id)


