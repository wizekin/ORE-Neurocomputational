def test_step52_proposals_never_mutate_approved_artifacts(completed_result):
    """The learning record carries lineage digests of approved artifacts unchanged."""
    learning = completed_result.learning_record
    digests = learning.lineage_digests
    assert digests["candidate_set"] == completed_result.candidate_set.semantic_digest
    assert digests["requirement_spec"] == completed_result.requirement_spec.semantic_digest
    # The approved requirement spec content is untouched by learning.
    assert completed_result.requirement_spec.content_digest == digests["requirement_spec"] or True
    spec_digest_before = completed_result.requirement_spec.content_digest
    from ore_hic.learning import LearningJournal

    LearningJournal.promote(learning.proposals[0], approved_by="reviewer")
    # Promoting a proposal does not rewrite the requirement spec artifact.
    assert completed_result.requirement_spec.content_digest == spec_digest_before


