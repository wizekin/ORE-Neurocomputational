def test_changed_artifact_requires_renewed_approval():
    """Approving one candidate set does not authorize a different one."""
    from ore_hic import CandidateSet

    compiler = build_compiler()
    result = run_to_completion(compiler)
    assert result.status == "COMPLETED"
    original = result.candidate_set

    # A modified candidate set (different selected candidate) has a new digest.
    modified = CandidateSet(
        artifact_id=original.artifact_id,
        model_id=original.model_id,
        candidates=original.candidates,
        comparisons=original.comparisons,
        selected_id="cand-003",
        shortlist=original.shortlist,
        deferred=original.deferred,
        version=original.version + 1,
    )
    assert modified.semantic_digest != original.semantic_digest
    from ore_hic import CompilationSession

    session = CompilationSession(user="u2")
    with pytest.raises(GateViolation):
        PythonGenerator().generate(session, result.algo_ir, modified, approved_digest=original.semantic_digest)


