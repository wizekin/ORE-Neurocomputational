"""ORE scientific reasoning layer: the Point 12 integrated scientific algorithm.

This package implements the integrated algorithm "Scientific, Geometric and
Physical-World AI" (source Point 12 of ``Most Intelligent Systems 01-24.txt``, ORE
integration priority 22 of 24). It gives ORE the ability to reason about scientific
and physical-world problems by selecting representations, equations, models, and
solvers that respect the structure of each domain, validating their outputs
independently, quantifying uncertainty, recording provenance, and updating knowledge
only when evidence warrants it.

Scope statement: this is the reference implementation of the proposed architecture.
Specialized external services (AlphaFold-family, RFdiffusion, GNoME/MatterGen,
GraphCast/GenCast, GTSAM bindings) are optional, individually versioned integrations
behind stable interfaces; the local reference models exercise the same contracts and
are not claims of domain-leading predictive skill.
"""
