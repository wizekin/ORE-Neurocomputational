"""Validated contracts for hippocampal replay and sleep-dependent systems consolidation.

Inputs are caller-supplied neural observations or model-level abstractions. They do not imply that
the corresponding numerical variables are represented explicitly by biological neurons.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
import math
from typing import Any, Mapping, Sequence


def _finite_vector(name: str, values: Sequence[float], allow_empty: bool = False) -> tuple[float, ...]:
    """Convert a sequence to finite floats and enforce its required non-empty policy."""
    vector = tuple(float(value) for value in values)
    if not allow_empty and not vector:
        raise ValueError(f"{name} must not be empty")
    if any(not math.isfinite(value) for value in vector):
        raise ValueError(f"{name} values must be finite")
    return vector


def _unit_interval(name: str, value: float) -> float:
    """Validate and return a finite normalized scalar between zero and one."""
    number = float(value)
    if not math.isfinite(number) or not 0.0 <= number <= 1.0:
        raise ValueError(f"{name} must be finite and in [0, 1]")
    return number


def _jsonable(value: Any) -> Any:
    """Convert dataclasses, mappings, sequences, and array-like values to JSON-compatible values."""
    if hasattr(value, "to_dict"):
        return _jsonable(value.to_dict())
    if hasattr(value, "tolist"):
        return _jsonable(value.tolist())
    if hasattr(value, "item") and callable(value.item):
        return _jsonable(value.item())
    if isinstance(value, Mapping):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [_jsonable(item) for item in value]
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    return repr(value)


@dataclass(frozen=True, slots=True)
class HippocampalTrace:
    """One retained episode available for later replay.

    Features are event-specific. Sequence optionally stores ordered feature vectors; absent
    sequence data is represented as a one-element sequence. Priority attributes are explicit
    model inputs, not inferred psychological facts or known neural ranking variables. All feature
    vectors in one processor must match its configured input size.
    """

    trace_id: str
    features: Sequence[float]
    sequence: Sequence[Sequence[float]] = ()
    recency: float = 1.0
    salience: float = 0.5
    value: float = 0.5
    goal_relevance: float = 0.5
    interference_risk: float = 0.0
    context_id: str = "unspecified"
    baseline_performance: float | None = None

    def __post_init__(self) -> None:
        """Validate trace identity, feature content, priority inputs, and baseline performance."""
        if not isinstance(self.trace_id, str) or not self.trace_id.strip():
            raise ValueError("trace_id must be a non-empty string")
        if not isinstance(self.context_id, str) or not self.context_id.strip():
            raise ValueError("context_id must be a non-empty string")
        features = _finite_vector("features", self.features)
        sequence = tuple(_finite_vector("sequence item", item) for item in self.sequence)
        if any(len(item) != len(features) for item in sequence):
            raise ValueError("every sequence vector must match the trace feature dimension")
        for name in ("recency", "salience", "value", "goal_relevance", "interference_risk"):
            object.__setattr__(self, name, _unit_interval(name, getattr(self, name)))
        baseline = self.baseline_performance
        if baseline is not None:
            object.__setattr__(self, "baseline_performance",
                               _unit_interval("baseline_performance", baseline))
        object.__setattr__(self, "features", features)
        object.__setattr__(self, "sequence", sequence)

    def to_dict(self) -> dict[str, Any]:
        """Return the trace and explicit provenance as a JSON-compatible mapping."""
        return _jsonable(asdict(self))


@dataclass(frozen=True, slots=True)
class ReplayOpportunity:
    """One observed offline interval and candidate neural replay event.

    Sleep state is one of wake, awake_rest, NREM, or REM. Rhythm measures may be extracted
    from recordings or generated by a model. Slow-oscillation phase can be supplied directly
    or estimated from slow_oscillation_signal; spindle and ripple evidence are supplied as
    envelope/z-score summaries so event detection remains distinct from trace identification.
    Performance values are optional external measurements, not generated by the processor.
    """

    opportunity_id: str
    sleep_state: str = "nrem"
    sleep_state_confidence: float = 1.0
    timestamp_ms: float = 0.0
    slow_oscillation_phase_rad: float | None = None
    slow_oscillation_signal: Sequence[float] = ()
    sample_rate_hz: float = 100.0
    spindle_envelope: float = 0.0
    spindle_duration_ms: float = 0.0
    spindle_phase_rad: float | None = None
    ripple_band_z: float = 0.0
    sharp_wave_z: float = 0.0
    ripple_duration_ms: float = 0.0
    partial_cue: Sequence[float] | None = None
    pre_post_interval_ms: float = 0.0
    observed_pre_performance: float | None = None
    observed_post_performance: float | None = None
    replay_direction: str = "forward"

    def __post_init__(self) -> None:
        """Normalize event observations and reject unsupported states or invalid timing data."""
        if not isinstance(self.opportunity_id, str) or not self.opportunity_id.strip():
            raise ValueError("opportunity_id must be a non-empty string")
        state = self.sleep_state.strip().lower()
        if state not in {"wake", "awake_rest", "nrem", "rem"}:
            raise ValueError("sleep_state must be wake, awake_rest, nrem, or rem")
        object.__setattr__(self, "sleep_state", state)
        object.__setattr__(self, "sleep_state_confidence",
                           _unit_interval("sleep_state_confidence", self.sleep_state_confidence))
        for name in ("timestamp_ms", "sample_rate_hz", "spindle_envelope", "spindle_duration_ms",
                     "ripple_band_z", "sharp_wave_z", "ripple_duration_ms", "pre_post_interval_ms"):
            value = float(getattr(self, name))
            if not math.isfinite(value) or (name in {"timestamp_ms", "spindle_duration_ms",
                    "ripple_duration_ms", "spindle_envelope"} and value < 0.0):
                raise ValueError(f"{name} must be finite and non-negative")
            if name == "sample_rate_hz" and value <= 0.0:
                raise ValueError("sample_rate_hz must be positive")
            object.__setattr__(self, name, value)
        for name in ("slow_oscillation_phase_rad", "spindle_phase_rad"):
            value = getattr(self, name)
            if value is not None:
                value = float(value)
                if not math.isfinite(value):
                    raise ValueError(f"{name} must be finite when supplied")
                object.__setattr__(self, name, value)
        signal = _finite_vector("slow_oscillation_signal", self.slow_oscillation_signal,
                                allow_empty=True)
        object.__setattr__(self, "slow_oscillation_signal", signal)
        if self.partial_cue is not None:
            object.__setattr__(self, "partial_cue", _finite_vector("partial_cue", self.partial_cue))
        for name in ("observed_pre_performance", "observed_post_performance"):
            value = getattr(self, name)
            if value is not None:
                object.__setattr__(self, name, _unit_interval(name, value))
        direction = self.replay_direction.strip().lower()
        if direction not in {"forward", "reverse"}:
            raise ValueError("replay_direction must be forward or reverse")
        object.__setattr__(self, "replay_direction", direction)

    def to_dict(self) -> dict[str, Any]:
        """Serialize the supplied offline observations without adding inferred values."""
        return _jsonable(asdict(self))


@dataclass(frozen=True, slots=True)
class SleepConsolidationConfig:
    """Engineering parameters for a reproducible hippocampal-cortical replay simulation.

    Population sizes, thresholds, learning rates, and time constants are model settings rather
    than universal physiological constants. The default sleep gate targets NREM; awake-rest
    replay can be enabled as a separate mode. Feature vectors have a fixed configured width.
    """

    input_size: int = 16
    hippocampal_units: int = 32
    cortical_units: int = 48
    sleep_state_threshold: float = 0.65
    allow_awake_rest: bool = True
    spindle_envelope_threshold: float = 0.30
    min_spindle_duration_ms: float = 250.0
    swr_score_threshold: float = 1.35
    min_ripple_duration_ms: float = 15.0
    max_ripple_duration_ms: float = 180.0
    replay_temperature: float = 0.65
    pattern_iterations: int = 8
    replay_compression: float = 0.25
    preferred_up_phase_rad: float = 0.0
    learning_rate: float = 0.012
    eligibility_tau_ms: float = 250.0
    stdp_tau_ms: float = 35.0
    max_weight_step: float = 0.02
    max_abs_weight: float = 1.5
    integration_rate: float = 0.035
    separation_strength: float = 0.025
    homeostatic_rate: float = 0.012
    target_activity: float = 0.30
    homeostatic_gain_min: float = 0.55
    homeostatic_gain_max: float = 1.75
    consolidation_rate: float = 0.08
    destabilization_rate: float = 0.025
    random_seed: int = 31
    max_trace_count: int = 4096

    def __post_init__(self) -> None:
        """Validate dimensions, event thresholds, learning controls, and bounded state values."""
        if min(self.input_size, self.hippocampal_units, self.cortical_units,
               self.pattern_iterations, self.max_trace_count) < 2:
            raise ValueError("population sizes, iteration count, and trace capacity must be >= 2")
        for name in ("sleep_state_threshold", "spindle_envelope_threshold",
                     "replay_compression", "target_activity"):
            _unit_interval(name, getattr(self, name))
        if self.min_spindle_duration_ms < 0.0 or self.min_ripple_duration_ms < 0.0:
            raise ValueError("event durations must be non-negative")
        if self.max_ripple_duration_ms < self.min_ripple_duration_ms:
            raise ValueError("max_ripple_duration_ms must be >= min_ripple_duration_ms")
        if self.swr_score_threshold < 0.0 or self.replay_temperature <= 0.0:
            raise ValueError("SWR threshold must be non-negative and replay temperature positive")
        if self.eligibility_tau_ms <= 0.0 or self.stdp_tau_ms <= 0.0:
            raise ValueError("eligibility and STDP time constants must be positive")
        if self.max_weight_step <= 0.0 or self.max_abs_weight <= 0.0:
            raise ValueError("weight limits must be positive")
        if not 0.0 <= self.homeostatic_gain_min <= self.homeostatic_gain_max:
            raise ValueError("homeostatic gain bounds are invalid")
        for name in ("learning_rate", "integration_rate", "separation_strength",
                     "homeostatic_rate", "consolidation_rate", "destabilization_rate"):
            value = float(getattr(self, name))
            if not math.isfinite(value) or value < 0.0:
                raise ValueError(f"{name} must be finite and non-negative")

    def to_dict(self) -> dict[str, Any]:
        """Return all numerical controls for experiment reproducibility."""
        return asdict(self)


@dataclass(slots=True)
class SleepConsolidationResult:
    """Inspectable result for one replay opportunity and all 18 source-ordered operations."""

    opportunity_id: str
    selected_trace_id: str | None
    operation_trace: list[dict[str, Any]]
    sleep_gate: dict[str, Any]
    rhythm_events: dict[str, Any]
    replay_sequence: list[list[float]]
    replay_timestamps_ms: list[float]
    alignment: dict[str, Any]
    reinstatement: dict[str, Any]
    plasticity: dict[str, Any]
    integration: dict[str, Any]
    homeostasis: dict[str, Any]
    retrieval_support: dict[str, Any]
    consolidation_state: dict[str, Any]
    validation: dict[str, Any]
    cortical_activity: list[float]
    biological: dict[str, Any]
    logger: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        """Serialize outputs, model diagnostics, and skipped-stage provenance."""
        return _jsonable({"schema": "ore.sleep_systems_consolidation.1.0", **asdict(self)})
